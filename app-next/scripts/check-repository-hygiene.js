const fs = require("fs"), path = require("path"), assert = require("assert");
const root = path.resolve(__dirname, "../..");
const read = (name) => fs.readFileSync(path.join(root, name), "utf8");
const pkg = JSON.parse(read("app-next/package.json")), lock = JSON.parse(read("app-next/package-lock.json"));
assert.equal(pkg.version, lock.version); assert.equal(pkg.version, lock.packages[""].version);
assert.equal(pkg.engines.node, ">=24");
assert.equal(pkg.engines.node, lock.packages[""].engines.node);
assert(!pkg.build.nsis, "inactive NSIS configuration must not return to the portable build");
for (const old of ["app-next/.github/workflows/release.yml", "app-next/.github/copilot-instructions.md", "app-next/PACKAGING-FIXES.md", "app-next/docs/chat.md", ".github/scripts/inject_public_servers_html.py", "app-next/lib/palfields.js", ".github/workflows/super-experimental-next-build.yml"]) assert(!fs.existsSync(path.join(root, old)), `Retired path returned: ${old}`);
for (const license of ["LICENSE", "LICENSE.txt", "app-next/LICENSE"]) assert(fs.statSync(path.join(root, license)).size > 1000, `License notice missing: ${license}`);
assert(read("app-next/app/api/worlds/[id]/settings/route.js").includes('@/lib/server-fields'));
const fields = require("../lib/server-fields");
assert(fields.allFields().some((field) => field.key === "OwnerId"));
const workflow = read(".github/workflows/windows-release.yml"), publisher = read(".github/scripts/publish-windows-release.ps1");
const parsedWorkflow = require("js-yaml").load(workflow);
assert(parsedWorkflow.on.push.branches.includes("main"));
assert.equal(parsedWorkflow.permissions.contents, "write");
assert(parsedWorkflow.jobs["build-windows"].steps.some((step) => step.name === "Publish self-update prerelease" && step.run.includes("publish-windows-release.ps1")));
assert(workflow.includes("npm run test:release") && workflow.includes("publish-windows-release.ps1"));
assert(workflow.includes("GITHUB_SHA") && workflow.includes("BUILD-INFO.txt"));
assert(publisher.includes('$tag = "v$version"') && publisher.includes("tags are never moved"));
assert(!publisher.includes("github.run_number") && !publisher.includes("--force"));
assert(read("app-next/CHANGELOG.md").includes(pkg.version));
assert(read(".gitignore").includes("app-next/.rsdw-*/") && read(".gitignore").includes("app-next/.env.*"));
console.log("Repository hygiene: single release workflow, version/lock consistency, current settings path, retained licenses and immutable version tags: OK");
